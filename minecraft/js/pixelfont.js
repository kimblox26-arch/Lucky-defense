const PixelFont = {
  /** 문자열 픽셀 폭 (스케일 1 기준, 글자 간격 1px 포함) */
  measure(text, scale = 1, spacing = 1) {
    if (!text.length) return 0;
    return (text.length * (PIXEL_FONT_W + spacing) - spacing) * scale;
  },

  /**
   * 캔버스에 픽셀 텍스트를 그린다.
   * opts: { color, shadow, shadowColor, spacing, align, mask }
   *  - mask(px, py, cx, cy) 가 false를 반환하면 해당 픽셀은 건너뜀 (타이핑/디졸브 연출용)
   */
  draw(ctx, text, x, y, scale = 4, opts = {}) {
    const color = opts.color || '#ffffff';
    const spacing = opts.spacing == null ? 1 : opts.spacing;
    const align = opts.align || 'left';
    const width = PixelFont.measure(text, scale, spacing);
    let ox = x;
    if (align === 'center') ox = x - width / 2;
    else if (align === 'right') ox = x - width;

    if (opts.shadow) {
      const so = opts.shadowOffset == null ? scale : opts.shadowOffset;
      PixelFont.draw(ctx, text, ox + so, y + so, scale, {
        ...opts, color: opts.shadowColor || 'rgba(0,0,0,0.55)', shadow: false, align: 'left',
      });
    }

    ctx.fillStyle = color;
    for (let i = 0; i < text.length; i++) {
      const ch = text[i].toUpperCase();
      const g = PIXEL_GLYPHS[ch] || PIXEL_GLYPHS['?'];
      const gx = ox + i * (PIXEL_FONT_W + spacing) * scale;
      for (let row = 0; row < PIXEL_FONT_H; row++) {
        const line = g[row];
        for (let col = 0; col < PIXEL_FONT_W; col++) {
          if (line[col] !== '#') continue;
          if (opts.mask && !opts.mask(col, row, i, gx + col * scale, y + row * scale)) continue;
          ctx.fillRect(gx + col * scale, y + row * scale, scale, scale);
        }
      }
    }
    return width;
  },

  /** 글자별 픽셀 좌표 목록 — 파티클처럼 날아오는 연출에 사용 */
  pixels(text, scale = 4, spacing = 1) {
    const out = [];
    for (let i = 0; i < text.length; i++) {
      const ch = text[i].toUpperCase();
      const g = PIXEL_GLYPHS[ch];
      if (!g) continue;
      for (let row = 0; row < PIXEL_FONT_H; row++) {
        for (let col = 0; col < PIXEL_FONT_W; col++) {
          if (g[row][col] !== '#') continue;
          out.push({
            x: i * (PIXEL_FONT_W + spacing) * scale + col * scale,
            y: row * scale,
            col, row, index: i,
          });
        }
      }
    }
    return out;
  },
};
